#!/usr/bin/env python3
"""Generate an mwldarm linker command file for a dsd module.

Sections come from the module's delinks.txt; cross-module references are forced
to their absolute addresses from every module's symbols.txt (main is linked on
its own, so ITCM/DTCM/overlay symbols must be supplied as constants).

  python tools/scripts/gen_lcf.py --module main -o build/link/main.lcf <objs...>

Exit 0 ok / 1 unresolved symbols / 2 error.
"""
import argparse
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CFG = os.path.join(ROOT, "config", "arm9")
OBJDUMP = os.environ.get("OBJDUMP", "arm-none-eabi-objdump")

SECTION_RE = re.compile(
    r"^\s+(\S+)\s+start:0x([0-9a-fA-F]+)\s+end:0x([0-9a-fA-F]+)"
    r"\s+kind:(\w+)\s+align:(\d+)")
SYM_RE = re.compile(r"^(\S+)\s+kind:\S*?(?:function|bss|data|rodata)\S*?\s+.*?addr:0x([0-9a-fA-F]+)",
                    re.IGNORECASE)
ADDR_RE = re.compile(r"^(\S+)\s+.*\baddr:0x([0-9a-fA-F]+)")

# Linker-defined SDK symbols: the symbol's ADDRESS is the value (see CLAUDE.md
# "Near-match decision tree" -- address-as-value link symbols).
LINK_SYMS = {
    "SDK_MAIN_ARENA_LO": 0x021277C0,
    "SDK_AUTOLOAD_ITCM_END": 0x01FFA580,
    "SDK_AUTOLOAD_DTCM_END": 0x027E1200,
    "SDK_AUTOLOAD_DTCM_START": 0x027E0000,
    "SDK_IRQ_STACKSIZE": 0x800,
    "SDK_SYS_STACKSIZE": 0x0,
}


def module_dir(module):
    if module == "main":
        return CFG
    if module in ("itcm", "dtcm"):
        return os.path.join(CFG, module)
    return os.path.join(CFG, "overlays", module)


def read_sections(module):
    path = os.path.join(module_dir(module), "delinks.txt")
    out = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            m = SECTION_RE.match(line)
            if m:
                out.append({
                    "name": m.group(1),
                    "start": int(m.group(2), 16),
                    "end": int(m.group(3), 16),
                    "kind": m.group(4),
                    "align": int(m.group(5)),
                })
    if not out:
        sys.exit("error: no sections parsed from %s" % path)
    return out


def read_all_symbols():
    """addr-by-name across every module (main + autoloads + overlays)."""
    syms = {}
    for dirpath, _dirs, files in os.walk(CFG):
        if "symbols.txt" not in files:
            continue
        with open(os.path.join(dirpath, "symbols.txt"), encoding="utf-8") as fh:
            for line in fh:
                m = ADDR_RE.match(line)
                if m:
                    addr = int(m.group(2), 16)
                    # Thumb targets need bit 0 set or the linker emits bl, not blx.
                    if "function(thumb" in line:
                        addr |= 1
                    syms.setdefault(m.group(1), addr)
    return syms


def undefined_symbols(objs):
    und = set()
    defined = set()
    for obj in objs:
        try:
            out = subprocess.run([OBJDUMP, "-t", obj], capture_output=True,
                                 text=True, check=True).stdout
        except (OSError, subprocess.CalledProcessError) as exc:
            sys.exit("error: objdump failed on %s: %s" % (obj, exc))
        for line in out.splitlines():
            parts = line.split()
            if len(parts) < 2:
                continue
            name = parts[-1]
            if not name or name.startswith("$"):
                continue
            if "*UND*" in line:
                und.add(name)
            elif any(p.startswith(".") for p in parts):
                defined.add(name)   # has a real section => defined here
    return und - defined


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--module", default="main")
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("objects", nargs="+")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()

    sections = read_sections(args.module)
    syms = read_all_symbols()
    und = undefined_symbols(args.objects)

    forced, missing = {}, []
    for name in sorted(und):
        if name in LINK_SYMS:
            forced[name] = LINK_SYMS[name]
        elif name in syms:
            forced[name] = syms[name]
        else:
            missing.append(name)

    ctor = next((s for s in sections if s["name"] == ".ctor"), None)
    if ctor:
        forced.setdefault("ARM9_CTOR_START", ctor["start"])
        forced.setdefault("ARM9_CTOR_END", ctor["end"])
    # these two are named in the SDK's own template; harmless if unreferenced
    for name in ("ARM9_CTOR_START", "ARM9_CTOR_END"):
        if name in missing:
            missing.remove(name)

    origin = sections[0]["start"]
    lines = [
        "# GENERATED by tools/scripts/gen_lcf.py -- do not edit",
        "MEMORY {",
        "    %s (RWX) : ORIGIN=0x%08x, LENGTH=0x0" % (args.module, origin),
        "}",
        "",
        "SECTIONS {",
    ]
    # mwldarm wants the pad at the END of a block ("add .=ALIGN(n) before } >> main"),
    # so each section aligns the START of the next one. Reproduces the .ctor->.data
    # 8-byte gap exactly; a no-op wherever the sections already abut.
    for i, sec in enumerate(sections):
        op = ">" if i == 0 else ">>"
        nxt = sections[i + 1] if i + 1 < len(sections) else None
        pad = " . = ALIGN(0x%x);" % nxt["align"] if nxt and nxt["align"] > 1 else ""
        lines.append("    %-11s: { *(%s)%s } %s %s"
                     % (sec["name"], sec["name"], pad, op, args.module))
    lines.append("")
    for name in sorted(forced):
        lines.append("    %s = 0x%08x;" % (name, forced[name]))
    lines.append("}")

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")

    print("%s: %d sections, %d forced symbols, %d unresolved"
          % (args.output, len(sections), len(forced), len(missing)))
    if missing:
        for name in missing[:20] if not args.verbose else missing:
            print("  UNRESOLVED: %s" % name)
        if not args.verbose and len(missing) > 20:
            print("  ... %d more (-v for all)" % (len(missing) - 20))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
